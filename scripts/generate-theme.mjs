import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const theme = JSON.parse(readFileSync(new URL("../styles/theme.json", import.meta.url), "utf8"));
const entries = [
  ...Object.entries(theme.colors),
  ...Object.entries(theme.motion).map(([name, value]) => [`motion-${name}`, value]),
  ...Object.entries(theme.shadows).map(([name, value]) => [`shadow-${name}`, value]),
  ...Object.entries(theme.sizes).map(([name, value]) => [`size-${name}`, value]),
  ...Object.entries(theme.fonts).map(([name, value]) => [`font-family-${name}`, value]),
];
const css = `/* Generated by npm run tokens from styles/theme.json. */\n:root {\n${entries.map(([name, value]) => `  --${name}: ${value};`).join("\n")}\n}\n`;
writeFileSync(new URL("../styles/theme.generated.css", import.meta.url), css);

// Next.js already supplies sharp. Rasterize our existing vector for email
// clients, which do not reliably display SVG, without remote image hosting.
const basket = JSON.parse(readFileSync(new URL("../styles/basket.json", import.meta.url), "utf8"));
const markRadius = 32 * parseFloat(theme.sizes["radius-control"]) / parseFloat(theme.sizes["brand-mark"]);
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" rx="${markRadius.toFixed(2)}" fill="${theme.colors.brand}"/><path transform="translate(4 4)" d="${basket.path}" fill="none" stroke="${theme.colors.surface}" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round"/></svg>`;
const imageSize = parseInt(theme.sizes["brand-mark"]) * 2;
const image = await sharp(Buffer.from(svg)).resize(imageSize, imageSize).png().toBuffer();
writeFileSync(new URL("../styles/email-brand.generated.json", import.meta.url), `${JSON.stringify({ base64: image.toString("base64") })}\n`);
writeFileSync(new URL("../app/icon.svg", import.meta.url), `${svg}\n`);

// iOS Home Screen icons need a PNG; keep its background opaque because iOS
// applies its own rounded mask.
const appleIcon = await sharp(Buffer.from(svg)).resize(180, 180)
  .flatten({ background: theme.colors.brand }).png().toBuffer();
writeFileSync(new URL("../app/apple-icon.png", import.meta.url), appleIcon);

mkdirSync(new URL("../public/icons/", import.meta.url), { recursive: true });
for (const size of [192, 512]) {
  const icon = await sharp(Buffer.from(svg)).resize(size, size)
    .flatten({ background: theme.colors.brand }).png().toBuffer();
  writeFileSync(new URL(`../public/icons/basket-${size}.png`, import.meta.url), icon);
}
